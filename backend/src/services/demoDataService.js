const Project = require('../models/Project');
const EnergyRecord = require('../models/EnergyRecord');

async function generateAndInsert(userId) {
    const project = await Project.create({
        name: 'Demo Solar + Wind Microgrid',
        description: 'Autogenerated synthetic demo project for testing RENEW-AI.',
        owner: userId,
        status: 'ready'
    });

    const records = [];
    const now = Date.now();
    const thirtyDaysAgo = now - 30 * 24 * 60 * 60 * 1000;
    
    let currentBatterySOC = 60; // starts at 60%
    const batteryCapacity = 500;
    let currentCloudCoverage = 20;

    for (let i = 0; i < 720; i++) {
        const timestamp = new Date(thirtyDaysAgo + i * 3600000);
        const hour = timestamp.getHours();
        
        // Random walk for cloud coverage 0-80
        currentCloudCoverage = Math.max(0, Math.min(80, currentCloudCoverage + (Math.random() * 10 - 5)));
        
        let solarGeneration = 0;
        if (hour >= 6 && hour <= 18) {
            const noise = Math.random() * 10 - 5;
            solarGeneration = Math.max(0, 150 * Math.sin(Math.PI * (hour - 6) / 12) * (1 - currentCloudCoverage/100) + noise);
        }
        
        const windGeneration = Math.max(0, 50 + 30 * Math.sin(hour/24 * 2 * Math.PI) + (Math.random() * 30 - 15));
        const solarIrradiance = solarGeneration * (1000 / 150); // rough approximation
        const temperature = 20 + 8 * Math.sin(2 * Math.PI * (hour - 6) / 24) + (Math.random() * 6 - 3);
        const humidity = 60 + 20 * Math.random();
        const windSpeed = 8 + 4 * Math.random();
        const energyDemand = 80 + 40 * Math.sin(Math.PI * (hour - 8) / 16) + (Math.random() * 20 - 10);
        const gridPrice = 0.08 + 0.06 * Math.sin(Math.PI * (hour - 8) / 16) + (Math.random() * 0.02 - 0.01);
        const gridAvailability = Math.random() > 0.01;
        const totalCapacity = 400; // 300 solar + 100 wind
        
        const totalGen = solarGeneration + windGeneration;
        const surplus = totalGen - energyDemand;
        
        if (surplus > 0) {
            currentBatterySOC = Math.min(95, currentBatterySOC + (surplus / batteryCapacity) * 100);
        } else {
            currentBatterySOC = Math.max(10, currentBatterySOC - (Math.abs(surplus) / batteryCapacity) * 100);
        }

        records.push({
            projectId: project._id,
            timestamp,
            solarGeneration,
            windGeneration,
            totalCapacity,
            temperature,
            solarIrradiance,
            cloudCoverage: currentCloudCoverage,
            humidity,
            windSpeed,
            windDirection: Math.random() * 360,
            rainProbability: Math.random() * 100,
            batteryCapacity,
            batterySOC: currentBatterySOC,
            chargeRate: surplus > 0 ? surplus : 0,
            dischargeRate: surplus < 0 ? Math.abs(surplus) : 0,
            energyDemand,
            gridAvailability,
            gridPrice
        });
    }

    await EnergyRecord.insertMany(records);
    project.dataCount = records.length;
    await project.save();

    // Insert initial sample alerts
    const Alert = require('../models/Alert');
    await Alert.insertMany([
        {
            projectId: project._id,
            type: 'critical',
            message: 'Battery Storage Low Level Warning',
            detail: 'Battery SOC dropped to 18.5%, approaching safety threshold during evening peak demand.',
            timestamp: new Date(Date.now() - 15 * 60000)
        },
        {
            projectId: project._id,
            type: 'warning',
            message: 'High Cloud Coverage Forecasted',
            detail: 'Forecast predicts 75% cloud cover tomorrow at 14:00. Solar generation expected to drop by 40%.',
            timestamp: new Date(Date.now() - 45 * 60000)
        },
        {
            projectId: project._id,
            type: 'opportunity',
            message: 'High Grid Export Price Available',
            detail: 'Grid price spiked to $0.165/kWh. Recommend discharging battery surplus to maximize revenue.',
            timestamp: new Date(Date.now() - 120 * 60000)
        },
        {
            projectId: project._id,
            type: 'warning',
            message: 'Wind Speed Fluctuation Anomaly',
            detail: 'Wind gusts exceeding 14.5 m/s detected. Output variability may impact localized microgrid stability.',
            timestamp: new Date(Date.now() - 240 * 60000)
        },
        {
            projectId: project._id,
            type: 'opportunity',
            message: 'Optimal Solar Storage Window',
            detail: 'Peak solar surplus forecasted between 11:00 AM - 2:00 PM. Battery capacity ready at 42% SOC.',
            timestamp: new Date(Date.now() - 360 * 60000)
        }
    ]);
    
    return project._id;
}

module.exports = { generateAndInsert };

